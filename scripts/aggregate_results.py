#!/usr/bin/env python3
"""Aggregate outputs/test/**/results.json into the paper's result tables.

Implements the reporting rules used for every number in the paper:
  * A reported cell is a cross-seed mean over the 5 seeds (2021-2025).
  * Standard horizons are the canonical four prediction lengths only:
    {96, 192, 336, 720} for non-PEMS datasets, {12, 24, 48, 96} for PEMS —
    even when a results.json also contains the extended horizon (1080/144),
    it is excluded from the standard average.
  * "Avg" per dataset = mean over the four canonical horizons of the
    cross-seed means (identical to seed-mean of per-seed averages when
    coverage is complete; incomplete cells are reported with their seed count).
  * The extended-horizon table (--extended) is the single long horizon
    (1080 non-PEMS / 144 PEMS) on 11 datasets (exchange_rate excluded:
    its series is too short), read from the extended key of the standard
    results.json or from the `<run>_PLX` test directory.

Usage (from the repository root, after the experiments have been run):
    python scripts/aggregate_results.py                  # main table, MSE+MAE
    python scripts/aggregate_results.py --extended       # extended horizons
    python scripts/aggregate_results.py --per-horizon    # per-pred_len detail
    python scripts/aggregate_results.py --sdta-w 2       # SDTA at W=2

Any other run (W-sweep capacities, baseline axis sweeps, ablations) can be
aggregated with --pattern; docs/paper_code_map.md lists the run-name template
of every paper table. Examples:
    # W sweep, Small capacity, W=8:
    python scripts/aggregate_results.py --pattern \
      'SDTA-Small-W8=SDTA:arch_scan_Enc_1_Dec_1_Mask_0p5_SMax_12_Lmlp_1_W_8_S_{s}'
    # ablation: no anchor conditioning:
    python scripts/aggregate_results.py --pattern \
      'no-past=SDTA:arch_scan_Enc_2_Dec_1_Mask_0p5_NoPast_1_SMax_12_Lmlp_1_W_4_S_{s}'
    # random-init control (train outputs are tagged pre_no_pretrain):
    python scripts/aggregate_results.py --pre-tag no_pretrain --pattern \
      'random-init=SDTA:arch_scan_Enc_2_Dec_1_Mask_0p5_SMax_12_Lmlp_1_W_4_S_{s}'
    # CPC at K=4:
    python scripts/aggregate_results.py --pattern 'CPC-K4=CPC:arch_scan_Enc_2_K_4_Neg_64_S_{s}'
"""
from __future__ import annotations

import argparse
import json
import statistics
import sys
from pathlib import Path

SEEDS = [2021, 2022, 2023, 2024, 2025]
DATASETS = [
    "ETTh1", "ETTh2", "ETTm1", "ETTm2",
    "exchange_rate", "weather", "electricity", "traffic",
    "PEMS03", "PEMS04", "PEMS07", "PEMS08",
]
PEMS = {"PEMS03", "PEMS04", "PEMS07", "PEMS08"}
GROUPS = {
    "4-ETT": DATASETS[0:4],
    "4-Wide": DATASETS[4:8],
    "4-PEMS": DATASETS[8:12],
    "12-ds": DATASETS,
}

def canonical_pred_lens(dataset: str) -> list[str]:
    return ["12", "24", "48", "96"] if dataset in PEMS else ["96", "192", "336", "720"]

def extended_pred_len(dataset: str) -> str:
    return "144" if dataset in PEMS else "1080"

# Test-run directory name per (method, seed); the layout is
# outputs/test/{model_dir}/{dataset}/il96/pre_{run}/{run}/results.json
# and the run names are generated by entry/batch.py from the shipped configs.
def method_registry(sdta_w: int) -> dict[str, tuple[str, str]]:
    return {
        "SDTA": ("SDTA", f"arch_scan_Enc_2_Dec_1_Mask_0p5_SMax_12_Lmlp_1_W_{sdta_w}_S_{{s}}"),
        "TimeMAE_CI": ("TimeMAE_CI", "arch_scan_Enc_2_S_{s}"),
        "TimeDART": ("TimeDART", "arch_scan_Enc_2_Dec_1_S_{s}"),
        "TimeSiam": ("TimeSiam", "arch_scan_Enc_2_Dec_1_S_{s}"),
        "SimMTM": ("SimMTM", "arch_scan_Enc_2_S_{s}"),
        "PatchTST": ("PatchTST", "arch_scan_Enc_2_S_{s}"),
        "CPC": ("CPC", "arch_scan_Enc_2_K_1_Neg_64_S_{s}"),
        "SimTS": ("SimTS", "arch_scan_Enc_2_S_{s}"),
    }

def load_scores(root: Path, model_dir: str, dataset: str, run: str,
                pre_tag: str | None = None) -> tuple[dict | None, dict | None]:
    """Return (standard_scores, plx_scores) dicts {pred_len: {mse, mae}}."""
    base = root / "outputs" / "test" / model_dir / dataset / "il96" / f"pre_{pre_tag or run}"
    std = base / run / "results.json"
    plx = base / f"{run}_PLX" / "results.json"
    read = lambda p: json.loads(p.read_text())["scores"] if p.is_file() else None
    return read(std), read(plx)

def seed_values(root, model_dir, run_tpl, dataset, metric, pred_lens, extended,
                pre_tag=None):
    """Per-seed value list: mean over pred_lens (standard) or the long horizon."""
    vals = []
    for s in SEEDS:
        std, plx = load_scores(root, model_dir, dataset, run_tpl.format(s=s), pre_tag)
        if extended:
            key = extended_pred_len(dataset)
            src = std if std and key in std else plx
            if src and key in src:
                vals.append(src[key][metric])
        else:
            if std and all(k in std for k in pred_lens):
                vals.append(sum(std[k][metric] for k in pred_lens) / len(pred_lens))
    return vals

def fmt(vals: list[float], show_std: bool) -> str:
    if not vals:
        return "--"
    m = sum(vals) / len(vals)
    out = f"{m:.4f}"
    if show_std and len(vals) >= 2:
        out += f"±{statistics.stdev(vals):.4f}"
    if len(vals) != len(SEEDS):
        out += f"({len(vals)}s)"
    return out

def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1],
                    help="repository root containing outputs/ (default: this repo)")
    ap.add_argument("--metric", choices=["mse", "mae", "both"], default="both")
    ap.add_argument("--methods", nargs="*", default=None,
                    help="subset of methods (default: all 8)")
    ap.add_argument("--sdta-w", type=int, default=4, choices=[1, 2, 4, 8],
                    help="SDTA supervision-axis value W (default 4 = paper hero)")
    ap.add_argument("--extended", action="store_true",
                    help="extended-horizon table (1080/144, 11 datasets)")
    ap.add_argument("--per-horizon", action="store_true",
                    help="also print per-pred_len cross-seed means")
    ap.add_argument("--std", action="store_true", help="show cross-seed std")
    ap.add_argument("--seeds", nargs="+", type=int, default=None, metavar="SEED",
                    help="override the seed list (default 2021 2022 2023 2024 2025). "
                         "Needed for sub-sweeps run at a different seed budget: the "
                         "s_max sweep is 3 seeds, so pass --seeds 2021 2022 2023. "
                         "Without it the s_max=12 cells would be averaged over five "
                         "seeds and the s_max=18/24 cells over three, which is not a "
                         "matched comparison.")
    ap.add_argument("--pattern", action="append", default=None, metavar="LABEL=DIR:RUN_TPL",
                    help="aggregate a custom run instead of the built-in methods; "
                         "repeatable. RUN_TPL uses {s} for the seed, e.g. "
                         "'SDTA-W1=SDTA:arch_scan_Enc_1_Dec_1_Mask_0p5_SMax_12_Lmlp_1_W_1_S_{s}' "
                         "(see docs/paper_code_map.md for every table's run templates)")
    ap.add_argument("--pre-tag", default=None,
                    help="override the outputs/test pre_* directory tag; use 'no_pretrain' "
                         "for the random-init ablation")
    args = ap.parse_args()

    global SEEDS
    if args.seeds:
        SEEDS = list(args.seeds)

    if args.pattern:
        registry = {}
        for spec in args.pattern:
            try:
                label, rest = spec.split("=", 1)
                model_dir, run_tpl = rest.split(":", 1)
            except ValueError:
                print(f"bad --pattern {spec!r}; expected LABEL=DIR:RUN_TPL", file=sys.stderr)
                return 2
            registry[label] = (model_dir, run_tpl)
    else:
        registry = method_registry(args.sdta_w)
    methods = args.methods or list(registry)
    unknown = [m for m in methods if m not in registry]
    if unknown:
        print(f"unknown methods: {unknown}; choose from {list(registry)}", file=sys.stderr)
        return 2
    metrics = ["mse", "mae"] if args.metric == "both" else [args.metric]
    datasets = [d for d in DATASETS if not (args.extended and d == "exchange_rate")]

    for metric in metrics:
        title = "extended horizon" if args.extended else "standard horizons (canonical 4)"
        print(f"\n=== {metric.upper()} — {title}, W={args.sdta_w} for SDTA, seeds {SEEDS[0]}-{SEEDS[-1]} ===")
        print("dataset," + ",".join(methods))
        table: dict[str, dict[str, list[float]]] = {}
        for ds in datasets:
            row = []
            table[ds] = {}
            for m in methods:
                model_dir, run_tpl = registry[m]
                vals = seed_values(args.root, model_dir, run_tpl, ds, metric,
                                   canonical_pred_lens(ds), args.extended, args.pre_tag)
                table[ds][m] = vals
                row.append(fmt(vals, args.std))
            print(ds + "," + ",".join(row))
        print("group averages" + (" (mean±cross-seed std of the group average)" if args.std else "") + ":")
        for g, dss in GROUPS.items():
            dss = [d for d in dss if d in datasets]
            label = g if len(dss) == len(GROUPS[g]) else f"{len(dss)}-{g.split('-', 1)[1]}"
            row = []
            for m in methods:
                cells = [table[d][m] for d in dss]
                if any(not c for c in cells):
                    row.append("--")
                    continue
                mean = sum(sum(c) / len(c) for c in cells) / len(cells)
                out = f"{mean:.4f}"
                # Group-level std: std over per-seed group means, defined only
                # when every dataset has the full seed set (aligned by index).
                if args.std and all(len(c) == len(SEEDS) for c in cells):
                    per_seed = [sum(c[i] for c in cells) / len(cells) for i in range(len(SEEDS))]
                    out += f"±{statistics.stdev(per_seed):.4f}"
                row.append(out)
            print(label + "," + ",".join(row))

        if args.per_horizon and not args.extended:
            print("per-horizon cross-seed means:")
            for ds in datasets:
                for pl in canonical_pred_lens(ds):
                    row = []
                    for m in methods:
                        model_dir, run_tpl = registry[m]
                        vals = [
                            std[pl][metric]
                            for s in SEEDS
                            for std, _ in [load_scores(args.root, model_dir, ds,
                                                       run_tpl.format(s=s), args.pre_tag)]
                            if std and pl in std
                        ]
                        row.append(fmt(vals, args.std))
                    print(f"{ds},pl{pl}," + ",".join(row))
    return 0

if __name__ == "__main__":
    sys.exit(main())
